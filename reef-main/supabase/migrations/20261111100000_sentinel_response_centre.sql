
-- ============================================================================
-- REEF SENTINEL — Persistent Response Centre
-- Migration: 20261111100000
--
-- Creates persistent responses for deterministic Sentinel risk identifiers.
-- Plant and mine context is derived from the underlying operational record.
-- Includes role-based RLS and automatic response history.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. Persistent responses
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.sentinel_responses (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Matches deterministic IDs generated by src/lib/reef-sentinel.ts.
  risk_key text NOT NULL UNIQUE,

  risk_type text NOT NULL CHECK (
    risk_type IN (
      'equipment_lifespan',
      'maintenance_overdue',
      'inventory'
    )
  ),

  entity_type text NOT NULL CHECK (
    entity_type IN ('equipment', 'stock_item')
  ),

  entity_id uuid NOT NULL,

  -- Derived by the validation trigger; never trusted from the client.
  mine_id uuid REFERENCES public.mines(id) ON DELETE SET NULL,
  plant text REFERENCES public.plants(name) ON UPDATE CASCADE,

  status text NOT NULL DEFAULT 'open' CHECK (
    status IN ('open', 'in_progress', 'blocked', 'resolved')
  ),

  assigned_to uuid REFERENCES auth.users(id) ON DELETE SET NULL,

  response_notes text,
  target_date date,

  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT sentinel_response_risk_entity_check CHECK (
    (
      risk_type IN ('equipment_lifespan', 'maintenance_overdue')
      AND entity_type = 'equipment'
    )
    OR
    (
      risk_type = 'inventory'
      AND entity_type = 'stock_item'
    )
  )
);

CREATE INDEX IF NOT EXISTS idx_sentinel_responses_plant
  ON public.sentinel_responses (plant);

CREATE INDEX IF NOT EXISTS idx_sentinel_responses_mine
  ON public.sentinel_responses (mine_id);

CREATE INDEX IF NOT EXISTS idx_sentinel_responses_status
  ON public.sentinel_responses (status);

CREATE INDEX IF NOT EXISTS idx_sentinel_responses_assigned_to
  ON public.sentinel_responses (assigned_to);

CREATE INDEX IF NOT EXISTS idx_sentinel_responses_created_at
  ON public.sentinel_responses (created_at DESC);


-- Explicit table permissions.
REVOKE ALL ON public.sentinel_responses
  FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE
  ON public.sentinel_responses TO authenticated;

GRANT ALL
  ON public.sentinel_responses TO service_role;

ALTER TABLE public.sentinel_responses ENABLE ROW LEVEL SECURITY;


-- ---------------------------------------------------------------------------
-- 2. Validate risk identity and derive operational context
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.sentinel_validate_response()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  derived_mine_id uuid;
  derived_plant text;
  assignee_plant text;
BEGIN
  -- Existing responses cannot be reassigned to another risk.
  IF TG_OP = 'UPDATE' THEN
    IF NEW.risk_key IS DISTINCT FROM OLD.risk_key
       OR NEW.risk_type IS DISTINCT FROM OLD.risk_type
       OR NEW.entity_type IS DISTINCT FROM OLD.entity_type
       OR NEW.entity_id IS DISTINCT FROM OLD.entity_id THEN
      RAISE EXCEPTION
        'A Sentinel response cannot be reassigned to another risk';
    END IF;

    NEW.created_by := OLD.created_by;
    NEW.created_at := OLD.created_at;
  ELSE
    IF auth.role() = 'service_role' THEN
      NEW.created_by := COALESCE(NEW.created_by, auth.uid());
    ELSE
      NEW.created_by := auth.uid();
    END IF;
  END IF;

  -- The risk key must match the detector's deterministic identifier.
  IF NEW.risk_key IS DISTINCT FROM
     (NEW.risk_type || ':' || NEW.entity_id::text) THEN
    RAISE EXCEPTION
      'Sentinel risk key does not match its risk type and entity';
  END IF;

  -- Resolve mine and plant from the underlying operational record.
  IF NEW.risk_type IN ('equipment_lifespan', 'maintenance_overdue') THEN

    SELECT e.mine_id, m.plant
      INTO derived_mine_id, derived_plant
    FROM public.equipment e
    LEFT JOIN public.mines m ON m.id = e.mine_id
    WHERE e.id = NEW.entity_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION
        'The equipment record for this Sentinel risk does not exist';
    END IF;

    NEW.entity_type := 'equipment';

  ELSIF NEW.risk_type = 'inventory' THEN

    SELECT s.plant
      INTO derived_plant
    FROM public.stock_items s
    WHERE s.id = NEW.entity_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION
        'The stock item for this Sentinel risk does not exist';
    END IF;

    derived_mine_id := NULL;
    NEW.entity_type := 'stock_item';

  ELSE
    RAISE EXCEPTION
      'Unsupported Sentinel risk type: %', NEW.risk_type;
  END IF;

  -- Ignore any client-supplied mine or plant values.
  NEW.mine_id := derived_mine_id;
  NEW.plant := derived_plant;

  -- Assigned users must have a REEF profile and belong to the risk plant,
  -- unless they have the owner role.
  IF NEW.assigned_to IS NOT NULL THEN

    SELECT p.plant
      INTO assignee_plant
    FROM public.profiles p
    WHERE p.id = NEW.assigned_to;

    IF NOT FOUND THEN
      RAISE EXCEPTION
        'The assigned user does not have a REEF profile';
    END IF;

    IF NOT public.has_role(
      NEW.assigned_to,
      'owner'::public.app_role
    )
    AND (
      derived_plant IS NULL
      OR assignee_plant IS DISTINCT FROM derived_plant
    ) THEN
      RAISE EXCEPTION
        'The assigned user must belong to the risk plant';
    END IF;

  END IF;

  NEW.updated_at := now();

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sentinel_validate_response
  ON public.sentinel_responses;

CREATE TRIGGER trg_sentinel_validate_response
  BEFORE INSERT OR UPDATE ON public.sentinel_responses
  FOR EACH ROW
  EXECUTE FUNCTION public.sentinel_validate_response();


-- ---------------------------------------------------------------------------
-- 3. Response access policies
-- ---------------------------------------------------------------------------

-- Remove policies first so this migration can be rerun safely.
DROP POLICY IF EXISTS "sentinel_responses: read by plant"
  ON public.sentinel_responses;

DROP POLICY IF EXISTS "sentinel_responses: insert by role and plant"
  ON public.sentinel_responses;

DROP POLICY IF EXISTS "sentinel_responses: update by role and plant"
  ON public.sentinel_responses;


-- Read:
-- Owners can see all plants.
-- Other REEF users can see responses for their own plant.
CREATE POLICY "sentinel_responses: read by plant"
  ON public.sentinel_responses
  FOR SELECT
  TO authenticated
  USING (
    public.has_role(auth.uid(), 'owner'::public.app_role)
    OR (
      plant IS NOT NULL
      AND plant = (
        SELECT p.plant
        FROM public.profiles p
        WHERE p.id = auth.uid()
      )
      AND EXISTS (
        SELECT 1
        FROM public.user_roles ur
        WHERE ur.user_id = auth.uid()
      )
    )
  );


-- Insert:
-- Managers and supervisors can create responses for their plant.
-- Stock controllers can create inventory responses for their plant.
-- Owners can create responses across plants.
CREATE POLICY "sentinel_responses: insert by role and plant"
  ON public.sentinel_responses
  FOR INSERT
  TO authenticated
  WITH CHECK (
    public.has_role(auth.uid(), 'owner'::public.app_role)
    OR (
      plant IS NOT NULL
      AND plant = (
        SELECT p.plant
        FROM public.profiles p
        WHERE p.id = auth.uid()
      )
      AND (
        public.has_role(auth.uid(), 'manager'::public.app_role)
        OR public.has_role(auth.uid(), 'supervisor'::public.app_role)
        OR (
          risk_type = 'inventory'
          AND public.has_role(
            auth.uid(),
            'stock_controller'::public.app_role
          )
        )
      )
    )
  );


-- Update:
-- Managers and supervisors can update responses for their plant.
-- Stock controllers can update inventory responses for their plant.
-- Owners can update responses across plants.
CREATE POLICY "sentinel_responses: update by role and plant"
  ON public.sentinel_responses
  FOR UPDATE
  TO authenticated
  USING (
    public.has_role(auth.uid(), 'owner'::public.app_role)
    OR (
      plant IS NOT NULL
      AND plant = (
        SELECT p.plant
        FROM public.profiles p
        WHERE p.id = auth.uid()
      )
      AND (
        public.has_role(auth.uid(), 'manager'::public.app_role)
        OR public.has_role(auth.uid(), 'supervisor'::public.app_role)
        OR (
          risk_type = 'inventory'
          AND public.has_role(
            auth.uid(),
            'stock_controller'::public.app_role
          )
        )
      )
    )
  )
  WITH CHECK (
    public.has_role(auth.uid(), 'owner'::public.app_role)
    OR (
      plant IS NOT NULL
      AND plant = (
        SELECT p.plant
        FROM public.profiles p
        WHERE p.id = auth.uid()
      )
      AND (
        public.has_role(auth.uid(), 'manager'::public.app_role)
        OR public.has_role(auth.uid(), 'supervisor'::public.app_role)
        OR (
          risk_type = 'inventory'
          AND public.has_role(
            auth.uid(),
            'stock_controller'::public.app_role
          )
        )
      )
    )
  );

-- There is intentionally no authenticated DELETE policy.
-- Responses and their audit history should not be silently erased.


-- ---------------------------------------------------------------------------
-- 4. Response history
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.sentinel_response_history (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  response_id uuid NOT NULL
    REFERENCES public.sentinel_responses(id) ON DELETE CASCADE,

  event_type text NOT NULL CHECK (
    event_type IN (
      'created',
      'status_changed',
      'assignee_changed',
      'notes_updated',
      'target_date_changed'
    )
  ),

  old_status text,
  new_status text,

  old_assigned_to uuid,
  new_assigned_to uuid,

  note text,

  changed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sentinel_response_history_response
  ON public.sentinel_response_history (response_id, created_at DESC);


-- Authenticated users can read history, but cannot insert, update or delete it.
REVOKE ALL ON public.sentinel_response_history
  FROM PUBLIC, anon, authenticated;

GRANT SELECT
  ON public.sentinel_response_history TO authenticated;

GRANT ALL
  ON public.sentinel_response_history TO service_role;

ALTER TABLE public.sentinel_response_history ENABLE ROW LEVEL SECURITY;


-- Remove the policy first so this migration can be rerun safely.
DROP POLICY IF EXISTS "sentinel_response_history: read through response"
  ON public.sentinel_response_history;


-- Users can read history only when they can read its parent response.
CREATE POLICY "sentinel_response_history: read through response"
  ON public.sentinel_response_history
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.sentinel_responses r
      WHERE r.id = response_id
    )
  );


-- ---------------------------------------------------------------------------
-- 5. Automatically record response changes
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.sentinel_record_response_history()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN

  IF TG_OP = 'INSERT' THEN

    INSERT INTO public.sentinel_response_history (
      response_id,
      event_type,
      new_status,
      new_assigned_to,
      note,
      changed_by
    )
    VALUES (
      NEW.id,
      'created',
      NEW.status,
      NEW.assigned_to,
      NEW.response_notes,
      auth.uid()
    );

    RETURN NEW;
  END IF;


  IF NEW.status IS DISTINCT FROM OLD.status THEN

    INSERT INTO public.sentinel_response_history (
      response_id,
      event_type,
      old_status,
      new_status,
      changed_by
    )
    VALUES (
      NEW.id,
      'status_changed',
      OLD.status,
      NEW.status,
      auth.uid()
    );

  END IF;


  IF NEW.assigned_to IS DISTINCT FROM OLD.assigned_to THEN

    INSERT INTO public.sentinel_response_history (
      response_id,
      event_type,
      old_assigned_to,
      new_assigned_to,
      changed_by
    )
    VALUES (
      NEW.id,
      'assignee_changed',
      OLD.assigned_to,
      NEW.assigned_to,
      auth.uid()
    );

  END IF;


  IF NEW.response_notes IS DISTINCT FROM OLD.response_notes THEN

    INSERT INTO public.sentinel_response_history (
      response_id,
      event_type,
      note,
      changed_by
    )
    VALUES (
      NEW.id,
      'notes_updated',
      NEW.response_notes,
      auth.uid()
    );

  END IF;


  IF NEW.target_date IS DISTINCT FROM OLD.target_date THEN

    INSERT INTO public.sentinel_response_history (
      response_id,
      event_type,
      note,
      changed_by
    )
    VALUES (
      NEW.id,
      'target_date_changed',
      CASE
        WHEN NEW.target_date IS NULL THEN 'Target date cleared'
        ELSE 'Target date set to ' || NEW.target_date::text
      END,
      auth.uid()
    );

  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sentinel_response_history
  ON public.sentinel_responses;

CREATE TRIGGER trg_sentinel_response_history
  AFTER INSERT OR UPDATE ON public.sentinel_responses
  FOR EACH ROW
  EXECUTE FUNCTION public.sentinel_record_response_history();


